//! Reading a folder's existing Claude Code sessions from its history files.

use std::fs;
use std::path::{Path, PathBuf};

use agent_desk_core::claude::AgentEvent;
use agent_desk_core::claude::history::{
    HistoryEntry, HistoryWatcher, encode_project_dir, sessions_for_project,
};
use serde_json::{Value, json};

struct History {
    home: tempfile::TempDir,
    project: PathBuf,
    _work: tempfile::TempDir,
}

impl History {
    fn new() -> Self {
        let work = tempfile::tempdir().unwrap();
        let project = work.path().join("repo");
        fs::create_dir(&project).unwrap();
        Self {
            home: tempfile::tempdir().unwrap(),
            project,
            _work: work,
        }
    }

    fn dir(&self) -> PathBuf {
        let dir = self
            .home
            .path()
            .join("projects")
            .join(encode_project_dir(&self.project));
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn write(&self, file_name: &str, lines: &[Value]) {
        let body: String = lines.iter().map(|line| format!("{line}\n")).collect();
        fs::write(self.dir().join(file_name), body).unwrap();
    }

    fn user(&self, text: &str) -> Value {
        json!({"type": "user", "cwd": self.project, "sessionId": "s",
               "message": {"role": "user", "content": [{"type": "text", "text": text}]}})
    }

    fn assistant(&self, content: Value) -> Value {
        json!({"type": "assistant", "cwd": self.project, "sessionId": "s",
               "message": {"role": "assistant", "content": content}})
    }

    fn sessions(&self) -> Vec<agent_desk_core::claude::history::HistorySession> {
        sessions_for_project(self.home.path(), &self.project)
    }
}

const ID: &str = "10d97801-6bbf-442b-a03d-a252027fea22";

#[test]
fn encodes_folders_the_way_claude_code_names_them() {
    assert_eq!(
        encode_project_dir(Path::new("/tmp/claude-1000/-home-user-x")),
        "-tmp-claude-1000--home-user-x"
    );
    assert_eq!(
        encode_project_dir(Path::new("/home/user/my.repo_2")),
        "-home-user-my-repo-2"
    );
}

#[test]
fn reads_messages_and_tool_calls_in_order() {
    let h = History::new();
    h.write(&format!("{ID}.jsonl"), &[
        h.user("what files are here?"),
        h.assistant(json!([{"type": "thinking", "thinking": ""},
                           {"type": "tool_use", "id": "t1", "name": "Bash", "input": {"command": "ls"}}])),
        json!({"type": "user", "cwd": h.project, "message": {"role": "user",
               "content": [{"type": "tool_result", "tool_use_id": "t1", "content": "a.txt"}]}}),
        h.assistant(json!([{"type": "text", "text": "One file: a.txt"}])),
    ]);

    let sessions = h.sessions();
    assert_eq!(sessions.len(), 1);
    assert_eq!(sessions[0].session_id, ID);
    assert_eq!(
        sessions[0].entries,
        [
            HistoryEntry::User("what files are here?".into()),
            HistoryEntry::Agent(AgentEvent::ToolUse {
                id: "t1".into(),
                name: "Bash".into(),
                input: json!({"command": "ls"})
            }),
            HistoryEntry::Agent(AgentEvent::ToolResult {
                tool_use_id: "t1".into(),
                content: "a.txt".into(),
                is_error: false
            }),
            HistoryEntry::Agent(AgentEvent::AssistantText {
                text: "One file: a.txt".into()
            }),
        ]
    );
}

