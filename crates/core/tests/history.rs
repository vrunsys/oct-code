//! Reading a folder's existing Claude Code sessions from its history files.

use std::fs;
use std::path::{Path, PathBuf};

use agent_desk_core::claude::AgentEvent;
use agent_desk_core::claude::history::{
    HistoryEntry, HistoryWatcher, encode_project_dir, sessions_for_project,
};
use serde_json::{Value, json};

struct History {
    home: tempfile::TempDir,
    project: PathBuf,
    _work: tempfile::TempDir,
}

impl History {
    fn new() -> Self {
        let work = tempfile::tempdir().unwrap();
        let project = work.path().join("repo");
        fs::create_dir(&project).unwrap();
        Self {
            home: tempfile::tempdir().unwrap(),
            project,
            _work: work,
        }
    }

    fn dir(&self) -> PathBuf {
        let dir = self
            .home
            .path()
            .join("projects")
            .join(encode_project_dir(&self.project));
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn write(&self, file_name: &str, lines: &[Value]) {
        let body: String = lines.iter().map(|line| format!("{line}\n")).collect();
        fs::write(self.dir().join(file_name), body).unwrap();
    }

    fn user(&self, text: &str) -> Value {
        json!({"type": "user", "cwd": self.project, "sessionId": "s",
               "message": {"role": "user", "content": [{"type": "text", "text": text}]}})
    }

    fn assistant(&self, content: Value) -> Value {
        json!({"type": "assistant", "cwd": self.project, "sessionId": "s",
               "message": {"role": "assistant", "content": content}})
    }

    fn sessions(&self) -> Vec<agent_desk_core::claude::history::HistorySession> {
        sessions_for_project(self.home.path(), &self.project)
    }
}

const ID: &str = "10d97801-6bbf-442b-a03d-a252027fea22";

#[test]
fn encodes_folders_the_way_claude_code_names_them() {
    assert_eq!(
        encode_project_dir(Path::new("/tmp/claude-1000/-home-user-x")),
        "-tmp-claude-1000--home-user-x"
    );
    assert_eq!(
        encode_project_dir(Path::new("/home/user/my.repo_2")),
        "-home-user-my-repo-2"
    );
}

#[test]
fn reads_messages_and_tool_calls_in_order() {
    let h = History::new();
    h.write(&format!("{ID}.jsonl"), &[
        h.user("what files are here?"),
        h.assistant(json!([{"type": "thinking", "thinking": ""},
                           {"type": "tool_use", "id": "t1", "name": "Bash", "input": {"command": "ls"}}])),
        json!({"type": "user", "cwd": h.project, "message": {"role": "user",
               "content": [{"type": "tool_result", "tool_use_id": "t1", "content": "a.txt"}]}}),
        h.assistant(json!([{"type": "text", "text": "One file: a.txt"}])),
    ]);

    let sessions = h.sessions();
    assert_eq!(sessions.len(), 1);
    assert_eq!(sessions[0].session_id, ID);
    assert_eq!(
        sessions[0].entries,
        [
            HistoryEntry::User("what files are here?".into()),
            HistoryEntry::Agent(AgentEvent::ToolUse {
                id: "t1".into(),
                name: "Bash".into(),
                input: json!({"command": "ls"})
            }),
            HistoryEntry::Agent(AgentEvent::ToolResult {
                tool_use_id: "t1".into(),
                content: "a.txt".into(),
                is_error: false
            }),
            HistoryEntry::Agent(AgentEvent::AssistantText {
                text: "One file: a.txt".into()
            }),
        ]
    );
}

#[test]
fn uses_claude_codes_title_when_present() {
    let h = History::new();
    h.write(
        &format!("{ID}.jsonl"),
        &[
            h.user("what files are here?"),
            json!({"type": "ai-title", "aiTitle": "Folder file listing", "sessionId": ID}),
        ],
    );
    assert_eq!(
        h.sessions()[0].title.as_deref(),
        Some("Folder file listing")
    );
}

#[test]
fn skips_subagent_meta_and_command_lines() {
    let h = History::new();
    let mut sidechain = h.user("subagent prompt");
    sidechain["isSidechain"] = json!(true);
    let mut meta = h.user("Caveat: generated by a command");
    meta["isMeta"] = json!(true);
    h.write(
        &format!("{ID}.jsonl"),
        &[
            sidechain,
            meta,
            h.user("<command-name>/clear</command-name>"),
            h.user("real question"),
        ],
    );
    assert_eq!(
        h.sessions()[0].entries,
        [HistoryEntry::User("real question".into())]
    );
}

#[test]
fn ignores_a_session_recorded_in_another_folder() {
    // Folder names are encoded lossily ("a.b" and "a-b" collide), so the
    // session's own cwd decides whether it belongs to this project.
    let h = History::new();
    let mut other = h.user("from elsewhere");
    other["cwd"] = json!("/somewhere/else");
    h.write(&format!("{ID}.jsonl"), &[other]);
    assert!(h.sessions().is_empty());
}

#[test]
fn ignores_files_not_named_like_a_session() {
    let h = History::new();
    h.write("--resume-evil.jsonl", &[h.user("x")]);
    h.write("notes.txt", &[h.user("x")]);
    assert!(h.sessions().is_empty());
}

#[test]
fn malformed_lines_are_skipped_and_empty_sessions_dropped() {
    let h = History::new();
    fs::write(
        h.dir().join(format!("{ID}.jsonl")),
        format!("{{not json\n{}\n", h.user("hello")),
    )
    .unwrap();
    h.write(
        "0222ee39-2e20-4887-a779-9246dfce7c4f.jsonl",
        &[json!({"type": "summary"})],
    );
    let sessions = h.sessions();
    assert_eq!(sessions.len(), 1);
    assert_eq!(sessions[0].entries, [HistoryEntry::User("hello".into())]);
}

#[test]
fn missing_history_is_empty() {
    let h = History::new();
    assert!(h.sessions().is_empty());
}

#[test]
fn a_watcher_reports_a_session_again_only_after_its_file_changes() {
    let history = History::new();
    history.write(&format!("{ID}.jsonl"), &[history.user("one")]);
    let mut watcher = HistoryWatcher::new(history.home.path(), &history.project);

    assert_eq!(watcher.poll().len(), 1, "first poll reports what exists");
    assert!(watcher.poll().is_empty(), "nothing changed");

    let mut file = fs::OpenOptions::new()
        .append(true)
        .open(history.dir().join(format!("{ID}.jsonl")))
        .unwrap();
    let reply = history.assistant(json!([{"type": "text", "text": "two"}]));
    std::io::Write::write_all(&mut file, format!("{reply}\n").as_bytes()).unwrap();

    let changed = watcher.poll();
    assert_eq!(changed.len(), 1);
    assert_eq!(changed[0].entries.len(), 2);
    assert!(watcher.poll().is_empty());
}

#[test]
fn a_watcher_reports_a_session_created_after_it_started() {
    let history = History::new();
    let mut watcher = HistoryWatcher::new(history.home.path(), &history.project);
    assert!(watcher.poll().is_empty());
    history.write(&format!("{ID}.jsonl"), &[history.user("hello")]);
    assert_eq!(watcher.poll().len(), 1);
}
