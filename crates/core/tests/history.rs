#[test]
fn turns_from_history_end_with_their_time_and_tokens() {
    let history = History::new();
    let mut ask = history.user("one");
    ask["timestamp"] = json!("2026-11-25T06:35:14.000Z");
    let mut reply = history.assistant(json!([{"type": "text", "text": "two"}]));
    reply["timestamp"] = json!("2026-11-25T06:35:26.500Z");
    reply["message"]["id"] = json!("msg_1");
    reply["message"]["usage"] = json!({"input_tokens": 2, "cache_read_input_tokens": 98,
        "cache_creation_input_tokens": 0, "output_tokens": 30});
    let mut next = history.user("three");
    next["timestamp"] = json!("2026-11-25T06:40:00.000Z");
    history.write(&format!("{ID}.jsonl"), &[ask, reply, next]);

    let entries = &history.sessions()[0].entries;
    let done = entries
        .iter()
        .position(|e| matches!(e, HistoryEntry::Agent(AgentEvent::TurnDone { .. })))
        .expect("the first turn closes when the next message starts");
    assert!(matches!(
        &entries[done],
        HistoryEntry::Agent(AgentEvent::TurnDone {
            duration_ms: 12_500,
            cost_usd: None,
            ..
        })
    ));
    assert_eq!(entries[done + 1], HistoryEntry::User("three".into()));
    assert!(
        entries[..done].contains(&HistoryEntry::Agent(AgentEvent::Usage {
            message_id: Some("msg_1".into()),
            input_tokens: 100,
            output_tokens: 30,
        }))
    );
}

#[test]
fn parses_claude_codes_timestamps() {
    use agent_desk_core::claude::history::parse_timestamp_ms;
    assert_eq!(parse_timestamp_ms("1970-01-01T00:00:00.000Z"), Some(0));
    assert_eq!(
        parse_timestamp_ms("2026-11-25T06:35:14.383Z"),
        Some(1_795_588_514_383)
    );
    assert_eq!(
        parse_timestamp_ms("2024-02-29T12:00:00Z"),
        Some(1_709_208_000_000)
    );
    assert_eq!(parse_timestamp_ms("2026-13-01T00:00:00Z"), None);
    assert_eq!(parse_timestamp_ms("yesterday"), None);
}

#[test]
fn a_session_can_be_read_again_from_the_start() {
    let history = History::new();
    history.write(&format!("{ID}.jsonl"), &[history.user("one")]);
    let mut watcher = HistoryWatcher::new(history.home.path(), &history.project);
    watcher.poll();
    append(&history, &format!("{}\n", reply_two(&history)));

    watcher.reread(ID);
    let again = watcher.poll();
    assert!(again[0].from_start);
    assert_eq!(
        again[0].entries,
        [HistoryEntry::User("one".into()), text_two()]
    );
}

fn boundary(trigger: &str) -> Value {
    json!({"type": "system", "subtype": "compact_boundary", "content": "Conversation compacted",
           "compactMetadata": {"trigger": trigger, "preTokens": 100, "postTokens": 10}})
}

fn compact_summary(history: &History, text: &str) -> Value {
    let mut line = history.user(text);
    line["isCompactSummary"] = json!(true);
    line["isVisibleInTranscriptOnly"] = json!(true);
    line
}

#[test]
fn a_compaction_is_one_marker_with_its_summary_and_not_a_user_message() {
    let h = History::new();
    let summary = "This session is being continued from a previous conversation.";
    h.write(
        &format!("{ID}.jsonl"),
        &[
            h.user("one"),
            h.assistant(json!([{"type": "text", "text": "two"}])),
            boundary("auto"),
            compact_summary(&h, summary),
            h.user("three"),
        ],
    );

    let entries = &h.sessions()[0].entries;
    let without_turn_ends: Vec<_> = entries
        .iter()
        .filter(|entry| !matches!(entry, HistoryEntry::Agent(AgentEvent::TurnDone { .. })))
        .cloned()
        .collect();
    assert_eq!(
        without_turn_ends,
        [
            HistoryEntry::User("one".into()),
            HistoryEntry::Agent(AgentEvent::AssistantText { text: "two".into() }),
            HistoryEntry::Agent(AgentEvent::Compacted {
                trigger: "auto".into(),
                pre_tokens: Some(100),
                post_tokens: Some(10),
            }),
            HistoryEntry::Agent(AgentEvent::CompactSummary {
                text: summary.into()
            }),
            HistoryEntry::User("three".into()),
        ]
    );
}

#[test]
fn a_compaction_does_not_split_the_turn_it_happens_in() {
    let h = History::new();
    let mut ask = h.user("one");
    ask["timestamp"] = json!("2026-11-25T06:00:00.000Z");
    let mut summary = compact_summary(&h, "summary");
    summary["timestamp"] = json!("2026-11-25T06:01:30.000Z");
    let mut reply = h.assistant(json!([{"type": "text", "text": "two"}]));
    reply["timestamp"] = json!("2026-11-25T06:02:00.000Z");
    let mut next = h.user("three");
    next["timestamp"] = json!("2026-11-25T06:10:00.000Z");
    h.write(
        &format!("{ID}.jsonl"),
        &[ask, boundary("auto"), summary, reply, next],
    );

    let turn_ends: Vec<u64> = h.sessions()[0]
        .entries
        .iter()
        .filter_map(|entry| match entry {
            HistoryEntry::Agent(AgentEvent::TurnDone { duration_ms, .. }) => Some(*duration_ms),
            _ => None,
        })
        .collect();
    assert_eq!(
        turn_ends,
        [120_000],
        "one turn, from the question to the reply"
    );
}

#[test]
fn a_session_with_only_a_summary_is_not_a_conversation() {
    let h = History::new();
    h.write(
        &format!("{ID}.jsonl"),
        &[boundary("auto"), compact_summary(&h, "summary")],
    );
    assert!(h.sessions().is_empty());
}
